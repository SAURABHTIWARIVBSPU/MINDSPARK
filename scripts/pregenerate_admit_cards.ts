/**
 * Production Admit Card Pre-Generation Script
 * 
 * Safely generates single-page vector PDFs for all registered students
 * and stores them in private storage with indexed metadata.
 * 
 * Usage:
 *   npx tsx scripts/pregenerate_admit_cards.ts --dry-run     (Tests generation for first 10 students without saving)
 *   npx tsx scripts/pregenerate_admit_cards.ts --live        (Executes full batch generation for all students)
 */

import fs from 'fs';
import path from 'path';

// Ensure .env.local is loaded in standalone script runner
if (fs.existsSync('.env.local')) {
  const envContent = fs.readFileSync('.env.local', 'utf8');
  for (const line of envContent.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const [k, ...v] = trimmed.split('=');
    if (k && v.length && !process.env[k.trim()]) {
      process.env[k.trim()] = v.join('=').trim().replace(/^["']|["']$/g, '');
    }
  }
}

import { getDb } from '../src/lib/db';
import { getStorageAdapter } from '../src/lib/storage';
import { generateAdmitCardPdf } from '../src/lib/pdf/template';

async function main() {
  const isLive = process.argv.includes('--live');
  const isDryRun = !isLive || process.argv.includes('--dry-run');

  console.log(`=======================================================`);
  console.log(`  MIND-SPARK ADMIT CARD PRE-GENERATION PIPELINE`);
  console.log(`  Mode: ${isDryRun ? 'DRY-RUN (Simulated)' : 'LIVE EXECUTION'}`);
  console.log(`=======================================================\n`);

  const db = getDb();
  const storage = getStorageAdapter();
  const settings = await db.getSettings();

  console.log(`[1/4] Loaded system settings:`);
  console.log(`      Venue: ${settings.venue}`);
  console.log(`      Exam Date: ${settings.examDate} | Reporting: ${settings.reportingTime}\n`);

  console.log(`[2/4] Fetching registered students...`);
  const allStudents = [];
  let page = 1;
  const pageSize = 400;
  while (true) {
    const queryResult = await db.getStudents({ status: 'ACTIVE', page, pageSize });
    console.log(`      Page ${page}: fetched ${queryResult.students.length} rows (total reported: ${queryResult.total})`);
    if (!queryResult.students.length) break;
    allStudents.push(...queryResult.students);
    if (queryResult.students.length < pageSize) break;
    page++;
  }

  // Strictly filter to official registered candidates (MS2611*), excluding test candidates (MS26TEST*)
  const officialEligibleStudents = allStudents.filter(
    (s) => s.registrationNumber.startsWith('MS2611') && s.status === 'ACTIVE'
  );
  console.log(`      Found ${allStudents.length} total active records in DB.`);
  console.log(`      Filtered to ${officialEligibleStudents.length} official candidates (excluded ${allStudents.length - officialEligibleStudents.length} test records).\n`);

  const targetStudents = isDryRun ? officialEligibleStudents.slice(0, 10) : officialEligibleStudents;
  console.log(`[3/4] Processing ${targetStudents.length} candidates in batches...`);

  const startTime = Date.now();
  let successCount = 0;
  let failCount = 0;
  let totalBytes = 0;

  const batchSize = 25;
  for (let i = 0; i < targetStudents.length; i += batchSize) {
    const batch = targetStudents.slice(i, i + batchSize);
    
    await Promise.all(
      batch.map(async (student) => {
        try {
          // Generate vector PDF in memory (~16ms)
          const pdfBytes = await generateAdmitCardPdf(student, settings);
          totalBytes += pdfBytes.length;

          if (!isDryRun) {
            const fileName = `AdmitCard_${student.registrationNumber}.pdf`;
            const { fileId, storageType } = await storage.saveFile(fileName, pdfBytes, 'application/pdf');

            await db.saveAdmitCard({
              studentId: student.studentId,
              registrationNumber: student.registrationNumber,
              fileId,
              storageType,
              templateVersion: 'v1',
              sourceDataHash: 'v1',
              status: 'READY',
              generatedAt: new Date().toISOString(),
              updatedAt: new Date().toISOString(),
            });
          }
          successCount++;
        } catch (err: any) {
          failCount++;
          console.error(`      [FAIL] ${student.registrationNumber} (${student.name}):`, err.message);
        }
      })
    );

    const progressPct = (((i + batch.length) / targetStudents.length) * 100).toFixed(1);
    process.stdout.write(`\r      Progress: ${i + batch.length}/${targetStudents.length} (${progressPct}%)`);
  }

  const durationMs = Date.now() - startTime;
  console.log(`\n\n[4/4] Pipeline Complete!`);
  console.log(`      Successful: ${successCount}`);
  console.log(`      Failed: ${failCount}`);
  console.log(`      Total Generated Bytes: ${totalBytes} bytes (${(totalBytes / 1024).toFixed(1)} KB)`);
  console.log(`      Average Size: ${successCount ? (totalBytes / successCount / 1024).toFixed(2) : 0} KB`);
  console.log(`      Total Elapsed Time: ${(durationMs / 1000).toFixed(2)} seconds`);
  console.log(`      Throughput: ${(successCount / (durationMs / 1000)).toFixed(1)} admit cards / second\n`);

  if (isDryRun) {
    console.log(`[NOTE] This was a DRY-RUN. To execute live pre-generation, run with --live.`);
  }
}

main().catch((err) => {
  console.error('\nFatal error during pre-generation:', err);
  process.exit(1);
});
